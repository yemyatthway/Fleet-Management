  Id BIGINT NOT NULL AUTO_INCREMENT,
  RoleId VARCHAR(80) NOT NULL,
  ModuleKey VARCHAR(80) NOT NULL,
  Action VARCHAR(40) NOT NULL,
  EntityId VARCHAR(80) NOT NULL,
  Description TEXT NOT NULL,
