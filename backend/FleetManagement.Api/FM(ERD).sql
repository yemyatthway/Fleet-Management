  CustomerName VARCHAR(160) NOT NULL,
  Department VARCHAR(120) NOT NULL,
  CostCenter VARCHAR(80) NULL,
  VehicleId VARCHAR(40) NOT NULL,
  VehiclePlate VARCHAR(40) NOT NULL,
  TrailerNumber VARCHAR(80) NULL,
  DriverName VARCHAR(120) NOT NULL,
  CoDriverName VARCHAR(120) NULL,
  DispatcherName VARCHAR(120) NOT NULL,
  CargoType VARCHAR(120) NOT NULL,
  LoadWeightKg DECIMAL(18,2) NOT NULL DEFAULT 0,
  LoadVolumeM3 DECIMAL(18,2) NOT NULL DEFAULT 0,
  PickupLocation VARCHAR(160) NOT NULL,
  DropoffLocation VARCHAR(160) NOT NULL,
  PickupContact VARCHAR(160) NULL,
  DropoffContact VARCHAR(160) NULL,
  DepartureDateTime VARCHAR(40) NOT NULL,
  EstimatedArrival VARCHAR(40) NOT NULL,
  ActualArrival VARCHAR(40) NULL,
  PlannedDistanceKm DECIMAL(18,2) NOT NULL DEFAULT 0,
  StartingOdometerKm DECIMAL(18,2) NOT NULL DEFAULT 0,
  CurrentOdometerKm DECIMAL(18,2) NOT NULL DEFAULT 0,
  EndingOdometerKm DECIMAL(18,2) NULL,
  FuelIssuedLiters DECIMAL(18,2) NOT NULL DEFAULT 0,
  TollEstimate DECIMAL(18,2) NOT NULL DEFAULT 0,
  PermitRequired BOOLEAN NOT NULL DEFAULT FALSE,
