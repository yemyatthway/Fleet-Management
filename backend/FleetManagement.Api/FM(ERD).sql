CREATE TABLE Roles (
  Id VARCHAR(80) NOT NULL,
  Code VARCHAR(20) NOT NULL,
  Name VARCHAR(120) NOT NULL,
  Description VARCHAR(500) NOT NULL DEFAULT '',
  Status VARCHAR(30) NOT NULL DEFAULT 'Active',
  IsDeleted INT NOT NULL DEFAULT 0,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (Id),
  UNIQUE KEY UX_Roles_Code (Code)
) ENGINE=InnoDB;

CREATE TABLE RolePermissions (
  Id INT NOT NULL AUTO_INCREMENT,
  RoleId VARCHAR(80) NOT NULL,
  ModuleKey VARCHAR(80) NOT NULL,
  CanView BOOLEAN NOT NULL DEFAULT FALSE,
  CanCreate BOOLEAN NOT NULL DEFAULT FALSE,
  CanEdit BOOLEAN NOT NULL DEFAULT FALSE,
  CanDelete BOOLEAN NOT NULL DEFAULT FALSE,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (Id),
  UNIQUE KEY UX_RolePermissions_RoleId_ModuleKey (RoleId, ModuleKey),
  CONSTRAINT FK_RolePermissions_Roles FOREIGN KEY (RoleId) REFERENCES Roles(Id) ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE Users (
