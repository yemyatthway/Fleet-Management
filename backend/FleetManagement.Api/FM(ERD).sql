CREATE TABLE StatusHistories (
  Id BIGINT NOT NULL AUTO_INCREMENT,
  EntityType VARCHAR(80) NOT NULL,
  EntityId VARCHAR(80) NOT NULL,
  OldStatus VARCHAR(80) NULL,
  NewStatus VARCHAR(80) NOT NULL,
  RoleId VARCHAR(80) NOT NULL,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (Id),
  KEY IX_StatusHistories_RoleId (RoleId),
  KEY IX_StatusHistories_Entity (EntityType, EntityId),
  CONSTRAINT FK_StatusHistories_Roles FOREIGN KEY (RoleId) REFERENCES Roles(Id) ON DELETE RESTRICT
) ENGINE=InnoDB;

