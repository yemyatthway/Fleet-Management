CREATE TABLE Expenses (
  Id INT NOT NULL AUTO_INCREMENT,
  ExpenseDate VARCHAR(40) NOT NULL,
  ExpenseType VARCHAR(120) NOT NULL,
  VehicleId VARCHAR(40) NULL,
  TripNumber VARCHAR(80) NULL,
  DriverName VARCHAR(120) NULL,
  Amount DECIMAL(18,2) NOT NULL DEFAULT 0,
  Status VARCHAR(40) NOT NULL DEFAULT 'Active',
  Notes TEXT NULL,
  IsDeleted INT NOT NULL DEFAULT 0,
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (Id),
  KEY IX_Expenses_VehicleId (VehicleId),
  KEY IX_Expenses_TripNumber (TripNumber),
  CONSTRAINT FK_Expenses_Vehicles FOREIGN KEY (VehicleId) REFERENCES Vehicles(Id) ON DELETE SET NULL,
  CONSTRAINT FK_Expenses_Trips FOREIGN KEY (TripNumber) REFERENCES Trips(TripNumber) ON DELETE SET NULL
) ENGINE=InnoDB;

