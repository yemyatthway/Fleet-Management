  PRIMARY KEY (Id),
  KEY IX_AuditLogs_RoleId (RoleId),
  CONSTRAINT FK_AuditLogs_Roles FOREIGN KEY (RoleId) REFERENCES Roles(Id) ON DELETE RESTRICT
